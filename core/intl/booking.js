'use strict';

const crypto = require('crypto');
const { assertSlot } = require('./slots');

// store.run returns { changes } from node:sqlite and { changes: rowCount } from
// the Postgres shim. Unknown shapes (test doubles) are treated as "applied" so a
// future store wrapper cannot turn every write into a 409.
function changedRows(result) {
  if (result == null) return null;
  const raw = result.changes != null ? result.changes : result.rowCount;
  const n = Number(raw);
  return Number.isFinite(n) ? n : null;
}

function activeViewing(store, leadId, slotId) {
  return store.one(
    `SELECT * FROM i_viewing WHERE lead_id = ? AND slot_id = ? AND status != 'cancelled'`,
    [leadId, slotId],
  );
}

function slotTakenByOther(store, slotId, leadId) {
  return store.one(
    `SELECT id FROM i_viewing WHERE slot_id = ? AND status IN ('unconfirmed', 'confirmed') AND lead_id != ?`,
    [slotId, leadId],
  );
}

function reserveSlot(store, slotId) {
  if (!slotId) return true;
  const slot = store.one('SELECT status FROM i_slot WHERE id = ?', [slotId]);
  // Offered slots may be generated by the calendar instead of being rows in
  // i_slot; there is nothing to reserve in that case, and confirming them must
  // stay a no-op for the slot table (only the viewing row changes).
  if (!slot) return true;
  if (slot.status === 'removed') return false;
  if (slot.status === 'booked' || slot.status === 'held') return true;
  const n = changedRows(store.run(`UPDATE i_slot SET status = 'booked' WHERE id = ? AND status = 'free'`, [slotId]));
  return n !== 0;
}

function releaseSlot(store, slotId, viewingId) {
  if (!slotId) return;
  const other = store.one(
    `SELECT id FROM i_viewing WHERE slot_id = ? AND id != ? AND status IN ('unconfirmed', 'confirmed')`,
    [slotId, viewingId],
  );
  if (other) return;
  const slot = store.one('SELECT status FROM i_slot WHERE id = ?', [slotId]);
  if (!slot || !['booked', 'held'].includes(slot.status)) return;
  store.run(`UPDATE i_slot SET status = 'free' WHERE id = ? AND status IN ('booked', 'held')`, [slotId]);
}

function addSlot(api, config, propertyId, body, actor, { propertyRow, audit, fail }) {
  const property = propertyRow(api.store, propertyId);
  if (!property) return fail(404, 'not_found');
  const duration = body.duration_min == null ? 45 : Number(body.duration_min);
  if (![30, 45, 60].includes(duration)) return fail(400, 'invalid_slot');
  if (!body.start_utc || Number.isNaN(Date.parse(body.start_utc))) return fail(400, 'invalid_slot');
  const check = assertSlot(api.store, property, body.start_utc, duration, api.now());
  if (!check.ok) return { ok: false, status: 400, error_code: check.error_code };
  const id = `SL-${crypto.randomBytes(3).toString('hex')}`;
  api.store.run(
    `INSERT INTO i_slot (id, property_id, start_utc, duration_min, status, created_at) VALUES (?, ?, ?, ?, 'free', ?)`,
    [id, propertyId, check.start, duration, api.now().toISOString()],
  );
  audit(api.store, config, 'slot_add', null, { property_id: propertyId }, actor || 'broker');
  return { ok: true, id };
}

function bookViewing(api, config, leadId, slotId, actor, { loadLead, audit, fail }) {
  const lead = loadLead(api.store, leadId);
  const slot = slotId ? api.store.one('SELECT * FROM i_slot WHERE id = ?', [slotId]) : null;
  if (!lead || !slot) return fail(404, 'not_found');
  if (slot.status === 'removed') return fail(409, 'slot_unavailable');
  const leadProperty = String(lead.property_id || '');
  // 'general' means "property not identified yet": the broker picks the slot
  // explicitly, so only a known, different property is a mismatch.
  if (leadProperty && leadProperty !== 'general' && leadProperty !== String(slot.property_id || '')) {
    return fail(409, 'slot_property_mismatch');
  }
  const existing = activeViewing(api.store, leadId, slotId);
  if (existing) {
    if (slotTakenByOther(api.store, slotId, leadId)) return fail(409, 'slot_unavailable');
    if (!reserveSlot(api.store, slotId)) return fail(409, 'slot_unavailable');
    return { ok: true, id: existing.id, status: existing.status, reused: true };
  }
  if (slot.status !== 'free') return fail(409, 'slot_unavailable');
  const startMs = Date.parse(slot.start_utc);
  if (!Number.isFinite(startMs) || startMs <= api.now().getTime()) return fail(409, 'slot_unavailable');
  const id = `V-${crypto.randomBytes(3).toString('hex')}`;
  let result;
  try {
    result = api.store.transaction(() => {
      const claimed = changedRows(
        api.store.run(`UPDATE i_slot SET status = 'booked' WHERE id = ? AND status = 'free'`, [slotId]),
      );
      if (claimed === 0) return { conflicted: true };
      api.store.run(
        `INSERT INTO i_viewing (id, lead_id, property_id, slot_id, start_utc, status, created_at) VALUES (?, ?, ?, ?, ?, 'unconfirmed', ?)`,
        [id, leadId, slot.property_id, slotId, slot.start_utc, api.now().toISOString()],
      );
      audit(api.store, config, 'viewing_book', leadId, { slot_id: slotId }, actor || 'broker');
      return { id };
    });
  } catch (err) {
    // A UNIQUE hit means another request won the race for the same (lead, slot):
    // the slot UPDATE was rolled back, so report the existing reservation instead.
    if (!/UNIQUE|duplicate/i.test(String(err && err.message))) throw err;
    const again = activeViewing(api.store, leadId, slotId);
    if (again) return { ok: true, id: again.id, status: again.status, reused: true };
    return fail(409, 'slot_unavailable');
  }
  if (result && result.conflicted) {
    const again = activeViewing(api.store, leadId, slotId);
    if (again) return { ok: true, id: again.id, status: again.status, reused: true };
    return fail(409, 'slot_unavailable');
  }
  return { ok: true, id, status: 'unconfirmed' };
}

function setViewing(api, config, id, status, actor, { audit, fail }) {
  if (!['confirmed', 'cancelled'].includes(status)) return fail(400, 'invalid_viewing');
  const row = api.store.one('SELECT * FROM i_viewing WHERE id = ?', [id]);
  if (!row) return fail(404, 'not_found');
  if (row.status === status) return { ok: true, status };
  if (status === 'confirmed') {
    // Confirm only an unconfirmed reservation; a cancelled one stays cancelled.
    if (row.status !== 'unconfirmed') return fail(409, 'invalid_transition');
    const outcome = api.store.transaction(() => {
      const n = changedRows(
        api.store.run(`UPDATE i_viewing SET status = 'confirmed' WHERE id = ? AND status = 'unconfirmed'`, [id]),
      );
      if (n === 0) return { conflicted: true };
      if (slotTakenByOther(api.store, row.slot_id, row.lead_id)) return { busy: true };
      if (!reserveSlot(api.store, row.slot_id)) return { busy: true };
      api.store.run('UPDATE i_lead SET client_confirmed = 1 WHERE id = ?', [row.lead_id]);
      audit(api.store, config, 'viewing_confirm', row.lead_id, { viewing_id: id }, actor || 'broker');
      return { ok: true };
    });
    if (outcome.conflicted) {
      const again = api.store.one('SELECT status FROM i_viewing WHERE id = ?', [id]);
      if (again && again.status === 'confirmed') return { ok: true, status: 'confirmed' };
      return fail(409, 'invalid_transition');
    }
    if (outcome.busy) return fail(409, 'slot_unavailable');
    return { ok: true, status: 'confirmed' };
  }
  const outcome = api.store.transaction(() => {
    const n = changedRows(
      api.store.run(`UPDATE i_viewing SET status = 'cancelled' WHERE id = ? AND status <> 'cancelled'`, [id]),
    );
    if (n === 0) return { conflicted: true };
    releaseSlot(api.store, row.slot_id, id);
    audit(api.store, config, 'viewing_cancel', row.lead_id, { viewing_id: id }, actor || 'broker');
    return { ok: true };
  });
  if (outcome.conflicted) {
    const again = api.store.one('SELECT status FROM i_viewing WHERE id = ?', [id]);
    if (again && again.status === 'cancelled') return { ok: true, status: 'cancelled' };
    return fail(409, 'invalid_transition');
  }
  return { ok: true, status: 'cancelled' };
}

module.exports = {
  addSlot,
  bookViewing,
  setViewing,
};
